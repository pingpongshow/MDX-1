"""Generate 1-bpp bitmap fonts for the memory LCD as C arrays (firmware/core/ui/font_data.c).
Uses DejaVu Sans Mono shipped with matplotlib so the result is reproducible on any machine."""
import os, numpy as np
from PIL import Image, ImageDraw, ImageFont
import matplotlib
FONT = os.path.join(os.path.dirname(matplotlib.__file__), "mpl-data", "fonts", "ttf", "DejaVuSansMono.ttf")
FONT_B = os.path.join(os.path.dirname(matplotlib.__file__), "mpl-data", "fonts", "ttf", "DejaVuSansMono-Bold.ttf")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "firmware", "core", "ui", "font_data.c")

def render(name, path, px, cw, ch, chars, yoff=0):
    f = ImageFont.truetype(path, px)
    rows = []
    for c in chars:
        img = Image.new("L", (cw, ch), 0); d = ImageDraw.Draw(img)
        d.text((0, yoff), c, font=f, fill=255)
        a = (np.array(img) > 110).astype(np.uint8)
        # pack each row into ceil(cw/8) bytes, MSB first
        nb = (cw + 7) // 8
        packed = []
        for r in range(ch):
            v = 0
            for x in range(cw):
                v |= (int(a[r, x]) << (7 - (x % 8))) if False else 0
            bts = []
            for b in range(nb):
                byte = 0
                for bit in range(8):
                    x = b * 8 + bit
                    if x < cw and a[r, x]: byte |= 0x80 >> bit
                bts.append(byte)
            packed.extend(bts)
        rows.append(packed)
    lines = ["/* %s: %dx%d px, %d glyphs (ASCII %d..%d), %d bytes/row, row-major, MSB = leftmost pixel */" % (name, cw, ch, len(chars), ord(chars[0]), ord(chars[-1]), (cw + 7) // 8)]
    lines.append("const unsigned char %s[%d][%d] = {" % (name, len(chars), ch * ((cw + 7) // 8)))
    for c, p in zip(chars, rows):
        lines.append("  {" + ",".join("0x%02x" % b for b in p) + "}, /* '%s' */" % (c if c not in "\\'" else "\\" + c))
    lines.append("};")
    return "\n".join(lines)

ascii = "".join(chr(i) for i in range(32, 127))
digits = "0123456789-. "
src = ["/* Generated by tools/gen_fonts.py - do not edit. Fonts rendered from DejaVu Sans Mono (Bitstream Vera licence). */",
       '#include "font.h"',
       render("font_6x10", FONT, 10, 6, 10, ascii, -1),
       render("font_9x16", FONT, 15, 9, 16, ascii, -1),
       render("font_12x20_bold", FONT_B, 19, 12, 20, ascii, -1),
       render("font_28x48_digits", FONT_B, 48, 28, 48, digits, -4),
       "const font_t FONT_SMALL = {6, 10, 1, 32, 95, &font_6x10[0][0]};",
       "const font_t FONT_MED = {9, 16, 2, 32, 95, &font_9x16[0][0]};",
       "const font_t FONT_BOLD = {12, 20, 2, 32, 95, &font_12x20_bold[0][0]};",
       "const font_t FONT_DIGITS = {28, 48, 4, 0, 13, &font_28x48_digits[0][0]};  /* index by digits_index() */",
       ]
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w").write("\n".join(src) + "\n")
print("wrote", OUT, os.path.getsize(OUT) // 1024, "KB")
